def text(lang: str, key: str, **values: object) -> str:
    language = lang if lang in TEXTS else "EN"
    return TEXTS[language][key].format(**values)


def button_values(key: str) -> set[str]:
    return {translations[key] for translations in TEXTS.values()} | LEGACY_BUTTONS.get(key, set())
